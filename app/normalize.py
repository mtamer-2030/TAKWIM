"""تطبيع النصّ العربي قبل المطابقة (CLAUDE.md §12).

التطبيع إلزامي قبل أي مطابقة لقواعد الفحص؛ بدونه تفشل نصف القواعد على
كتابة التلاميذ (أشكال الألف والهمزات، التاء المربوطة، التشكيل، التطويل،
المسافات المتعدّدة). الوظيفة يقينية بحتة ولا تستدعي أي نموذج.
"""

from __future__ import annotations

import re

# التشكيل (الحركات) والعلامات فوق/تحت الحرف — تُحذف.
_TASHKEEL = re.compile(
    "[ؐ-ؚ"  # علامات قرآنية
    "ً-ٟ"   # الفتحة..التنوين وما بينها
    "ٰ"          # ألف خنجرية
    "ۖ-ۜ"
    "۟-ۨ"
    "۪-ۭ]"
)
_TATWEEL = "ـ"  # ـ

# جدول توحيد الحروف.
_MAP = {
    # الألف بأشكالها والهمزات المحمولة عليها → ا
    "أ": "ا",  # أ
    "إ": "ا",  # إ
    "آ": "ا",  # آ
    "ٱ": "ا",  # ٱ ألف الوصل
    # الهمزات المحمولة
    "ؤ": "و",  # ؤ → و
    "ئ": "ي",  # ئ → ي
    "ء": "",         # ء المفردة → تُحذف
    # التاء المربوطة والهاء
    "ة": "ه",  # ة → ه
    # الألف المقصورة والياء
    "ى": "ي",  # ى → ي
    # أرقام هندية → لاتينية (حتى تتطابق أطوال النصوص والأنماط)
    "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
    "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
}
_TRANSLATE = str.maketrans(_MAP)

_SPACES = re.compile(r"\s+")


def normalize(text: str | None) -> str:
    """يعيد نصّاً مطبّعاً جاهزاً للمطابقة (مقارنة substring أو regex)."""
    if not text:
        return ""
    s = str(text)
    s = _TASHKEEL.sub("", s)
    s = s.replace(_TATWEEL, "")
    s = s.translate(_TRANSLATE)
    s = _SPACES.sub(" ", s)
    return s.strip().lower()


def visible_length(text: str | None) -> int:
    """عدد المحارف الفعليّة التي كتبها التلميذ (للحجم الأدنى/الأقصى).

    يعتمد على النصّ الخام بعد إزالة الفراغ من الطرفين — مقياس «كم كتب»،
    لا النصّ المطبّع الذي يضغط المسافات.
    """
    if not text:
        return 0
    return len(str(text).strip())
