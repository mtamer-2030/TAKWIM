def build_template_docx() -> bytes:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = Document()
    for kind, text in _LINES:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        # أسطر الإرشاد تبدأ بـ # ليتجاهلها المحلّل، فيبقى القالب قابلاً للاستيراد كما هو.
        display = ("# " + text) if kind == "i" else text
        run = p.add_run(display)
        run.font.rtl = True
        if kind == "h":
            run.bold = True
            run.font.size = None
        elif kind == "i":
            run.italic = True
            # رمادي للإرشادات (تُحذف قبل الاستيراد؛ ولو بقيت لا تضرّ المحلّل).
            try:
                from docx.shared import RGBColor
                run.font.color.rgb = RGBColor(0x88, 0x88, 0x88)
            except Exception:
                pass
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
